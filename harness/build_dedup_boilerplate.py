"""Build the per-document-type boilerplate shingle list used by modules.dedup.

Usage: python -m harness.build_dedup_boilerplate [--corpus corpus_v2] [--min-df 0.2]
                                                 [--out config/dedup_boilerplate.yaml]

TRAIN-split (md5(inst_id) 70/15/15), CLEAN, DIGITAL documents only; the held-out corpus is refused.
A word-shingle is boilerplate of a doc type if it occurs in >= --min-df of that type's train docs.
Machine-written; rerun instead of editing.
"""
from __future__ import annotations

import argparse, collections
from pathlib import Path

import yaml

from harness import corpus_io as c
from modules import dedup as d


def build(min_df: float, cfg: dict) -> tuple[dict, dict]:
    df: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    n: collections.Counter = collections.Counter()
    for e in c.iter_docs(clean_only=True, split="train"):
        if c.is_scan(e):
            continue
        sh = d.shingles(d.page_text(e["path"]), cfg["shingle_words"])
        if not sh:
            continue
        n[e["doc_type"]] += 1
        df[e["doc_type"]].update(sh)
    return ({t: sorted(s for s, k in cn.items() if k >= min_df * n[t]) for t, cn in sorted(df.items())}, dict(n))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", default="corpus_v2"); ap.add_argument("--min-df", type=float, default=0.2)
    ap.add_argument("--out", default=str(c.REPO / "config" / "dedup_boilerplate.yaml"))
    a = ap.parse_args(argv)
    if "test" in Path(a.corpus).name:
        raise SystemExit("refusing to build a config from a held-out corpus")
    c.set_corpus(a.corpus)
    cfg = d.load_config()
    bp, n = build(a.min_df, cfg)
    Path(a.out).write_text(
        "# GENERATED by `python -m harness.build_dedup_boilerplate` - do not edit.\n"
        f"# source: {c.corpus_root().name}, split=train, clean digital documents, min_df={a.min_df}, "
        f"{cfg['shingle_words']}-word shingles (crc32)\n"
        + yaml.safe_dump({"source": {"corpus": c.corpus_root().name, "split": "train", "min_df": a.min_df,
                                     "train_docs_per_type": n},
                          "boilerplate_shingles": bp}, default_flow_style=None, width=160), encoding="utf-8")
    print("wrote", a.out, {t: len(v) for t, v in bp.items()})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
