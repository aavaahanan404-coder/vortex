"""Build the per-document-type font allow-list for pdf_forensics.

Usage: python -m harness.build_font_allowlist [--corpus corpus_v2] [--min-docs 2]
                                              [--out config/fonts_allowlist.yaml]

Uses TRAIN-split (md5(inst_id) 70/15/15), CLEAN (no non-control label), DIGITAL documents only.
The held-out corpus (corpus_test_v2) is refused. A font enters the list of a document type if at
least --min-docs distinct train documents of that type use it (names normalised: no ABCDEF+
subset prefix). Output is machine-written; never edit by hand, rerun this script.
"""
from __future__ import annotations

import argparse, collections
from pathlib import Path

import yaml

from harness import corpus_io as c

DEFAULT_OUT = c.REPO / "config" / "fonts_allowlist.yaml"


def build(min_docs: int = 2) -> dict:
    import pymupdf
    from modules.pdf_forensics import norm_font
    per_type: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    n_docs: collections.Counter = collections.Counter()
    for e in c.iter_docs(clean_only=True, split="train"):
        if c.is_scan(e):
            continue
        used = set()
        with pymupdf.open(e["path"]) as d:
            for pg in d:
                used |= {norm_font(s["font"]) for s in pg.get_texttrace() if s.get("type") == 0}
        n_docs[e["doc_type"]] += 1
        for f in used:
            per_type[e["doc_type"]][f] += 1
    return {"n_docs": dict(n_docs),
            "font_doc_counts": {t: dict(cn) for t, cn in per_type.items()},
            "fonts_by_doc_type": {t: sorted(f for f, k in cn.items() if k >= min_docs)
                                  for t, cn in sorted(per_type.items())}}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", default="corpus_v2"); ap.add_argument("--min-docs", type=int, default=2)
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    a = ap.parse_args(argv)
    if "test" in Path(a.corpus).name:
        raise SystemExit("refusing to build a config from a held-out corpus")
    c.set_corpus(a.corpus)
    res = build(a.min_docs)
    header = ("# GENERATED by `python -m harness.build_font_allowlist` - do not edit.\n"
              f"# source: {c.corpus_root().name}, split=train, clean digital documents only, min_docs={a.min_docs}\n")
    body = {"source": {"corpus": c.corpus_root().name, "split": "train", "min_docs": a.min_docs,
                       "train_clean_digital_docs_per_type": res["n_docs"]},
            "font_doc_counts": res["font_doc_counts"], "fonts_by_doc_type": res["fonts_by_doc_type"]}
    Path(a.out).write_text(header + yaml.safe_dump(body, sort_keys=False), encoding="utf-8")
    print(f"wrote {a.out}: " + ", ".join(f"{t}={len(v)} fonts/{res['n_docs'][t]} docs"
                                         for t, v in res["fonts_by_doc_type"].items()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
