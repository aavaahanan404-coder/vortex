"""Build config/templates.yaml from TRAIN-split clean DIGITAL documents of corpus_v2 (ground-truth field dicts).

Usage: python -m harness.build_templates [--corpus corpus_v2] [--out config/templates.yaml]
The held-out corpus is refused. Machine-written; rerun instead of editing.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from harness import corpus_io as c
from modules import templates_build as tb


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", default="corpus_v2"); ap.add_argument("--out", default=str(tb.DEFAULT_TEMPLATES))
    a = ap.parse_args(argv)
    if "test" in Path(a.corpus).name:
        raise SystemExit("refusing to build templates from a held-out corpus")
    c.set_corpus(a.corpus)
    samples = [(e["doc_type"], e["fields"], tuple(e["page_size_pt"]))
               for e in c.iter_docs(clean_only=True, split="train") if not c.is_scan(e)]
    t = tb.build_templates(samples)
    header = ("# GENERATED by `python -m harness.build_templates` - do not edit.\n"
              f"# source: {c.corpus_root().name}, split=train, clean digital documents ({len(samples)} documents)\n")
    Path(a.out).write_text(header + yaml.safe_dump(t, sort_keys=False, width=140), encoding="utf-8")
    print("wrote", a.out, {k: (len(v["scalars"]), len(v["tables"]), v["n_train_docs"]) for k, v in t.items()})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
