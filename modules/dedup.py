_IMG_EXT = {".png", ".jpg", ".jpeg", ".tif", ".tiff", ".bmp", ".webp"}


def load_config(path: Optional[str | Path] = None) -> dict:
    p = Path(path or DEFAULT_CONFIG)
    with open(p, encoding="utf-8") as fh:
        cfg = yaml.safe_load(fh)
    cfg["_boilerplate"] = {}
    bf = cfg.get("boilerplate_file")
    if bf and (p.parent / bf).exists():       # generated by harness.build_dedup_boilerplate (train split)
        with open(p.parent / bf, encoding="utf-8") as fh:
            raw = (yaml.safe_load(fh) or {}).get("boilerplate_shingles", {})
        cfg["_boilerplate"] = {t: set(v) for t, v in raw.items()}
    return cfg


# ----------------------------------------------------------------------------- signatures
def sha256_file(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def render_page1_gray(path: str | Path, width: int) -> np.ndarray:
    """Page 1 (or the image) as grayscale, resized to `width` px wide."""
    p = Path(path)
    if p.suffix.lower() in _IMG_EXT:
        img = cv2.imread(str(p), cv2.IMREAD_GRAYSCALE)
        if img is None:
            raise ValueError("unreadable image")
        h, w = img.shape
        return cv2.resize(img, (width, max(1, round(h * width / w))), interpolation=cv2.INTER_AREA)
    import pymupdf
    with pymupdf.open(str(p)) as d:
        if d.page_count == 0:
            raise ValueError("PDF has no pages")
        pg = d[0]
        z = width / pg.rect.width
        pm = pg.get_pixmap(matrix=pymupdf.Matrix(z, z), colorspace=pymupdf.csGRAY, alpha=False)
        return np.frombuffer(pm.samples, np.uint8).reshape(pm.height, pm.width).copy()


def phash_bits(gray: np.ndarray, hash_size: int = 16, highfreq: int = 4) -> Optional[np.ndarray]:
    """Perceptual hash: DCT of a (hash_size*highfreq)^2 thumbnail, top-left hash_size^2
    coefficients thresholded at their median (DC excluded). Returns a bool vector or None for a
    blank/flat page (a flat page has no meaningful hash)."""
    if float(gray.std()) < 3.0:
        return None
    n = hash_size * highfreq
    small = cv2.resize(gray, (n, n), interpolation=cv2.INTER_AREA).astype(np.float32)
    dct = cv2.dct(small)[:hash_size, :hash_size]
    flat = dct.flatten()
    med = np.median(flat[1:])
    return flat > med


def page_text(path: str | Path, max_pages: int = 5) -> str:
    p = Path(path)
    if p.suffix.lower() in _IMG_EXT:
        return ""
    import pymupdf
    with pymupdf.open(str(p)) as d:
        return "\n".join(d[i].get_text() for i in range(min(d.page_count, max_pages)))


def shingles(text: str, k: int = 3) -> set[int]:
    words = re.findall(r"[a-z0-9]+", text.lower())
    if len(words) < k:
        return set()
    return {zlib.crc32(" ".join(words[i:i + k]).encode()) for i in range(len(words) - k + 1)}


def _seeds(n_perm: int, seed: int) -> np.ndarray:
    rs = np.random.RandomState(seed)
    return rs.randint(0, 2**63 - 1, n_perm, dtype=np.int64).astype(np.uint64) * np.uint64(2) + np.uint64(1)


def _mix(z: np.ndarray) -> np.ndarray:
    """splitmix64 finalizer: a good 64-bit bit mixer (uint64 arithmetic wraps modulo 2^64)."""
    with np.errstate(over="ignore"):
        z = (z ^ (z >> np.uint64(30))) * np.uint64(0xBF58476D1CE4E5B9)
        z = (z ^ (z >> np.uint64(27))) * np.uint64(0x94D049BB133111EB)
        return z ^ (z >> np.uint64(31))


def minhash(sh: set[int], n_perm: int = 128, seed: int = 26261) -> Optional[np.ndarray]:
    """MinHash signature (n_perm uint64) of a set of shingle hashes; None for an empty set.
    Permutation i is x -> mix(x xor seed_i); the signature entry is the minimum over the set, so
    P(entries agree) = Jaccard(set_a, set_b)."""
    if not sh:
        return None
    x = np.fromiter(sh, dtype=np.uint64)
    return _mix(x[None, :] ^ _seeds(n_perm, seed)[:, None]).min(axis=1)


def signature(path: str | Path, cfg: Optional[dict] = None, doc_type: Optional[str] = None,
              fields: Optional[dict] = None) -> dict:
    """{sha256, phash (bool vector|None), minhash (array|None), n_shingles}. Raises on unreadable files.
    With a known doc_type, shingles that are boilerplate of that document type (config boilerplate
    file) are dropped first: documents issued from one template are otherwise ~100% similar."""
    cfg = cfg or load_config()
    sig = {"sha256": sha256_file(path), "phash": None, "minhash": None, "n_shingles": 0, "raster": True,
           "path": str(path), "fields": scalar_fields(fields, cfg.get("fv_min_conf", 0.6))}
    try:
        sig["phash"] = phash_bits(render_page1_gray(path, cfg["render_width"]), cfg["hash_size"], cfg["highfreq"])
    except Exception:
        pass
    try:
        text = page_text(path)
        sig["raster"] = not text.strip()          # no text layer: a scan / image-only page
        sh = shingles(text, cfg["shingle_words"])
        sh -= cfg.get("_boilerplate", {}).get(doc_type, set())
        sig["n_shingles"] = len(sh)
        if len(sh) >= cfg["min_shingles"]:
            sig["minhash"] = minhash(sh, cfg["n_perm"], cfg["seed"])
    except Exception:
        pass
    return sig


# ----------------------------------------------------------------------------- field-value match
def _nv(v) -> str:
    return re.sub(r"[^a-z0-9]", "", str(v).lower())


def scalar_fields(fields: Optional[dict], min_conf: float = 0.6) -> dict[str, str]:
    """{key: normalised value} of the scalar fields of an ExtractedDoc.fields dict (or of a plain {key: value} dict).
    Table cells (keys with an index), QR, seal and signature are not identity fields; fields the extractor itself
    read with conf < min_conf are left out (an unreliable OCR read must not count as a disagreement)."""
    out = {}
    for k, v in (fields or {}).items():
        if "[" in k or k in ("qr", "seal", "signature"):
            continue
        if isinstance(v, dict) and v.get("conf", 1.0) < min_conf:
            continue
        raw = v.get("value") if isinstance(v, dict) else v
        n = _nv(raw) if raw not in (None, "") else ""
        if n:
            out[k] = n
    return out


def values_agree(a: str, b: str, cfg: dict) -> bool:
    if a == b:
        return True
    return min(len(a), len(b)) >= cfg["fv_min_len"] and difflib.SequenceMatcher(None, a, b).ratio() >= cfg["fv_fuzzy_ratio"]


# ----------------------------------------------------------------------------- field-region match
def field_ink(path: str | Path, cfg: dict) -> np.ndarray:
    """Background-normalised, lightly smoothed ink map of page 1 (0..1), width cfg['field_width']."""
    g = render_page1_gray(path, cfg["field_width"]).astype(np.float32) + 1
    ink = np.clip(1 - g / cv2.GaussianBlur(g, (0, 0), cfg["field_bg_sigma"]), 0, 1)
    return cv2.GaussianBlur(ink, (0, 0), cfg["field_smooth"])


def field_boxes(inks: list[np.ndarray], cfg: dict) -> list[tuple]:
    """Variable-field boxes of a document type: where digital documents of the type differ from each
    other (per-pixel std across the stack), merged into text-line boxes. The fixed template is ignored."""
    h = min(m.shape[0] for m in inks)
    var = (np.stack([m[:h] for m in inks]).std(axis=0) > cfg["field_var_std"]).astype(np.uint8) * 255
    var = cv2.dilate(var, cv2.getStructuringElement(cv2.MORPH_RECT, (cfg["field_hdil"], cfg["field_vdil"])))
    n, _, st, _ = cv2.connectedComponentsWithStats(var)
    return [tuple(int(v) for v in st[i][:4]) for i in range(1, n) if st[i][4] >= cfg["field_min_area"]]


def field_crops(ink: np.ndarray, boxes: list[tuple], shape: tuple, cfg: dict) -> list[np.ndarray]:
    """Per-box crops padded by field_shift px (zero border), so the other document's crop can be
    searched +-shift px around the template."""
    if ink.shape[0] != shape[0]:
        ink = cv2.resize(ink, (shape[1], shape[0]), interpolation=cv2.INTER_AREA)
    s = cfg["field_shift"]
    pad = cv2.copyMakeBorder(ink, s, s, s, s, cv2.BORDER_CONSTANT, value=0)
    return [pad[y:y + h + 2 * s, x:x + w + 2 * s] for x, y, w, h in boxes]


def field_score(raster_crops: list[np.ndarray], digital_crops: list[np.ndarray], cfg: dict) -> float:
    """Mean over boxes of the best normalised cross-correlation of the scan's field text inside the
    digital page's box (+-field_shift px). Boxes empty on both sides are skipped; a box with ink only
    on the digital side counts 0."""
    s, vals = cfg["field_shift"], []
    for rc, dc in zip(raster_crops, digital_crops):
        t = rc[s:-s, s:-s]
        if t.shape[0] < 6 or t.shape[1] < 6:
            continue
        ink_r, ink_d = float(t.mean()), float(dc[s:-s, s:-s].mean())
        if max(ink_r, ink_d) < 0.01:
            continue
        if ink_r < 0.005 or dc.shape[0] < t.shape[0] or dc.shape[1] < t.shape[1]:
            vals.append(0.0)
            continue
        vals.append(float(cv2.matchTemplate(dc, t, cv2.TM_CCOEFF_NORMED).max()))
    return float(np.mean(vals)) if vals else 0.0


# ----------------------------------------------------------------------------- index
class Index:
    """In-memory signature store with vectorised comparison."""

    def __init__(self, cfg: Optional[dict] = None):
        self.cfg = cfg or load_config()
        self.docs: list[dict] = []
        self._pos: dict[str, int] = {}
        self._ph: Optional[np.ndarray] = None
        self._mh: Optional[np.ndarray] = None
        self._tc: dict = {}                         # per doc type: field boxes + crop cache (lazy)

    def add(self, doc_id: str, inst_id: Optional[str], doc_type: Optional[str], sig: dict) -> None:
        self._pos[doc_id] = len(self.docs)
        self.docs.append({"doc_id": doc_id, "inst_id": inst_id, "doc_type": doc_type, **sig})
        self._ph = self._mh = None                    # rebuilt lazily
        self._tc = {}
        self.__dict__.pop("_cv", None)

    def get(self, doc_id: str) -> Optional[dict]:
        i = self._pos.get(doc_id)
        return None if i is None else self.docs[i]

    def _mats(self):
        if self._ph is None:
            nb = self.cfg["hash_size"] ** 2
            self._ph = np.array([d["phash"] if d["phash"] is not None else np.zeros(nb, bool) for d in self.docs]) \
                if self.docs else np.zeros((0, nb), bool)
            self._has_ph = np.array([d["phash"] is not None for d in self.docs], bool)
            self._mh = np.array([d["minhash"] if d["minhash"] is not None else np.zeros(self.cfg["n_perm"], np.uint64)
                                 for d in self.docs]) if self.docs else np.zeros((0, self.cfg["n_perm"]), np.uint64)
            self._has_mh = np.array([d["minhash"] is not None for d in self.docs], bool)
        return self._ph, self._has_ph, self._mh, self._has_mh

    def similarities(self, sig: dict) -> tuple[np.ndarray, np.ndarray]:
        """(normalised Hamming distance of pHash [nan if either missing], MinHash Jaccard estimate [nan])."""
        ph, has_ph, mh, has_mh = self._mats()
        n = len(self.docs)
        dist = np.full(n, np.nan); jac = np.full(n, np.nan)
        if sig["phash"] is not None and n:
            dist = (ph != sig["phash"][None, :]).mean(axis=1)
            dist[~has_ph] = np.nan
        if sig["minhash"] is not None and n:
            jac = (mh == sig["minhash"][None, :]).mean(axis=1)
            jac[~has_mh] = np.nan
        return dist, jac

    def _common_values(self, doc_type: str) -> set:
        """(key, value) pairs that are template-constant for the type (frequent across the index): they say nothing
        about identity (e.g. tenure = Lease, status = Active) and are ignored."""
        cache = self.__dict__.setdefault("_cv", {})
        if doc_type not in cache:
            docs = [d for d in self.docs if d["doc_type"] == doc_type and d.get("fields")]
            cnt = collections.Counter((k, v) for d in docs for k, v in d["fields"].items())
            lim = max(self.cfg["fv_common_min_docs"], self.cfg["fv_common_df"] * len(docs))
            cache[doc_type] = {kv for kv, n in cnt.items() if n >= lim}
        return cache[doc_type]

    def value_matches(self, sig: dict, doc_id: str, inst_id: Optional[str], doc_type: Optional[str]) -> tuple[list, set]:
        """Pairs (at least one raster page) of one type whose identity field VALUES agree: of the fields that are not
        template-constant, at least fv_min_equal agree and at least fv_min_frac (0.95: essentially all) of those compared, and the compared
        fields must cover at least fv_min_coverage of all non-constant fields present on either side.
        Works from extracted values, so it sees through re-scanning, re-rendering and scanner noise (OCR typos tolerated).
        Near-total agreement is required on purpose: two institutions of ONE society legitimately share the society's
        registration number, name, date and office bearers while differing in the registered office (5 of 6 fields)."""
        cfg, mine = self.cfg, sig.get("fields") or {}
        if doc_type is None or not mine:
            return [], set()
        common = self._common_values(doc_type)
        out, undecided = [], set()
        for d in self.docs:
            if (d["doc_type"] != doc_type or d["doc_id"] == doc_id or not d.get("fields") or d["sha256"] == sig["sha256"]
                    or not (sig.get("raster") or d.get("raster"))
                    or (cfg["cross_institution_only"] and inst_id is not None and d["inst_id"] == inst_id)):
                continue
            theirs = d["fields"]
            union = {k for k in set(mine) | set(theirs)
                     if (k in mine and (k, mine[k]) not in common) or (k in theirs and (k, theirs[k]) not in common)}
            rare = [k for k in union if k in mine and k in theirs]
            # a field one side could not read (low extractor confidence) is neither agreement nor disagreement, but
            # the comparison must still cover nearly all identity fields, or the unreadable one may be the differing one
            if len(rare) < cfg["fv_min_rare"] or len(rare) < cfg["fv_min_coverage"] * len(union):
                undecided.add(d["doc_id"])                 # too few readable fields to decide either way
                continue
            eq = [k for k in rare if values_agree(mine[k], d["fields"][k], cfg)]
            if len(eq) >= cfg["fv_min_equal"] and len(eq) / len(rare) >= cfg["fv_min_frac"]:
                out.append({"doc_id": d["doc_id"], "inst_id": d["inst_id"], "doc_type": d["doc_type"],
                            "similarity": round(len(eq) / len(rare), 4), "method": "field_values",
                            "fields_compared": len(rare), "fields_equal": sorted(eq)})
        return out, undecided

    def _type_cache(self, doc_type: str) -> Optional[dict]:
        """Field boxes of a document type, learned from the digital documents in this index (no stored
        template). None when the index has too few digital documents of the type."""
        if doc_type in self._tc:
            return self._tc[doc_type]
        cfg = self.cfg
        dig = [d for d in self.docs if d["doc_type"] == doc_type and not d.get("raster") and d.get("path")]
        tc = None
        if len(dig) >= cfg["field_min_digital"]:
            inks = [field_ink(d["path"], cfg) for d in dig[:cfg["field_sample"]]]
            boxes = field_boxes(inks, cfg)
            if len(boxes) >= cfg["field_min_boxes"]:
                tc = {"boxes": boxes, "shape": (min(m.shape[0] for m in inks), inks[0].shape[1]), "crops": {}}
        self._tc[doc_type] = tc
        return tc

    def _crops_of(self, tc: dict, doc: dict) -> list[np.ndarray]:
        k = doc["doc_id"]
        if k not in tc["crops"]:
            tc["crops"][k] = field_crops(field_ink(doc["path"], self.cfg), tc["boxes"], tc["shape"], self.cfg)
        return tc["crops"][k]

    def field_matches(self, sig: dict, doc_id: str, inst_id: Optional[str], doc_type: Optional[str]) -> list[dict]:
        """Scan <-> digital pairs of one document type whose variable-field text agrees (field_score).
        A raster query is compared with the digital documents of the type, a digital query with the
        raster ones; raster-raster and digital-digital pairs are not compared here."""
        cfg = self.cfg
        if doc_type is None or not sig.get("path"):
            return []
        want_raster = not sig.get("raster")
        cands = [d for d in self.docs if d["doc_type"] == doc_type and d["doc_id"] != doc_id and d.get("path")
                 and bool(d.get("raster")) == want_raster and d["sha256"] != sig["sha256"]
                 and not (cfg["cross_institution_only"] and inst_id is not None and d["inst_id"] == inst_id)]
        if not cands:
            return []
        tc = self._type_cache(doc_type)
        if tc is None:
            return []
        if self.get(doc_id):
            mine = self._crops_of(tc, self.get(doc_id))
        else:
            mine = field_crops(field_ink(sig["path"], cfg), tc["boxes"], tc["shape"], cfg)
        out = []
        for d in cands:
            theirs = self._crops_of(tc, d)
            sc = field_score(mine, theirs, cfg) if sig.get("raster") else field_score(theirs, mine, cfg)
            if sc >= cfg["min_field_score"]:
                out.append({"doc_id": d["doc_id"], "inst_id": d["inst_id"], "doc_type": d["doc_type"],
                            "field_score": round(sc, 4), "similarity": round(sc, 4), "method": "field_regions",
                            "n_boxes": len(tc["boxes"])})
        return out


def build_index(items, cfg: Optional[dict] = None) -> Index:
    """items: iterable of (doc_id, inst_id, doc_type, path[, fields]); fields = extract's ExtractedDoc.fields (optional, enables
    the value-based near-duplicate channel). Unreadable files are skipped."""
    cfg = cfg or load_config()
    idx = Index(cfg)
    for it in items:
        doc_id, inst_id, doc_type, path = it[:4]
        try:
            idx.add(doc_id, inst_id, doc_type, signature(path, cfg, doc_type, it[4] if len(it) > 4 else None))
        except Exception:
            continue
    return idx


# ----------------------------------------------------------------------------- analysis
def find_matches(sig: dict, index: Index, doc_id: str = "", inst_id: Optional[str] = None,
                 doc_type: Optional[str] = None) -> dict[str, list[dict]]:
    """{'exact': [...], 'visual': [...], 'text': [...]} - strongest kind per other document."""
    cfg = index.cfg
    dist, jac = index.similarities(sig)
    out: dict[str, list[dict]] = {"exact": [], "visual": [], "text": []}
    for i, d in enumerate(index.docs):
        if d["doc_id"] == doc_id:
            continue
        same_inst = inst_id is not None and d["inst_id"] == inst_id
        if cfg["cross_institution_only"] and same_inst:
            continue
        base = {"doc_id": d["doc_id"], "inst_id": d["inst_id"], "doc_type": d["doc_type"]}
        if d["sha256"] == sig["sha256"]:
            out["exact"].append({**base, "similarity": 1.0})
            continue
        if doc_type is not None and d["doc_type"] != doc_type:      # fuzzy matches need the same type
            continue
        raster_pair = bool(sig.get("raster")) or bool(d.get("raster"))
        if (not np.isnan(dist[i]) and dist[i] <= cfg["max_hamming_frac"]
                and (raster_pair or not cfg["visual_raster_only"])):
            out["visual"].append({**base, "hamming_frac": round(float(dist[i]), 4),
                                  "similarity": round(1 - float(dist[i]), 4)})
            continue
        if not np.isnan(jac[i]) and jac[i] >= cfg["min_jaccard"]:
            out["text"].append({**base, "similarity": round(float(jac[i]), 4)})
    seen = {m["doc_id"] for m in out["visual"]}
    vm, undecided = index.value_matches(sig, doc_id, inst_id, doc_type)   # extracted field values agree
    for m in vm:
        if m["doc_id"] not in seen and m["doc_id"] not in {x["doc_id"] for x in out["exact"]}:
            out["visual"].append(m); seen.add(m["doc_id"])
    have_values = bool(sig.get("fields"))
    if cfg["field_regions_fallback"] or not have_values:
        for m in index.field_matches(sig, doc_id, inst_id, doc_type):     # scan <-> digital, field pixels
            other = index.get(m["doc_id"])
            # the pixel channel decides only where values could not: no fields on a side, or too few readable ones
            if m["doc_id"] not in seen and (not have_values or not other or not other.get("fields") or m["doc_id"] in undecided):
                out["visual"].append(m)
    for k in out:
        out[k].sort(key=lambda m: -m["similarity"])
        out[k] = out[k][:cfg["max_matches"]]
    return out


def analyze(path: str | Path, doc_id: str = "", index: Optional[Index] = None, inst_id: Optional[str] = None,
            doc_type: Optional[str] = None, cfg: Optional[dict] = None, fields: Optional[dict] = None) -> list[Finding]:
    """Compare one document against `index`. Never raises."""
    cfg = cfg or (index.cfg if index is not None else load_config())
    try:
        sig = (index.get(doc_id) if index is not None else None) or signature(path, cfg, doc_type, fields)
        if index is None:
            return [Finding("dedup_ok", MODULE, "info", 3, 0.0, "No index to compare against.", doc_id)]
        m = find_matches(sig, index, doc_id, inst_id, doc_type)
    except Exception as exc:
        return [Finding("dedup_unreadable", MODULE, "info", 3, 0.0,
                        "Could not check for duplicates because the file could not be read.", doc_id, None,
                        {"error": f"{type(exc).__name__}: {exc}"})]
    out: list[Finding] = []

    def names(ms): return ", ".join(x["doc_id"] for x in ms[:3])
    if m["exact"]:
        out.append(Finding("exact_duplicate", MODULE, "soft", 3, cfg["p_exact"],
                           f"This file is byte-for-byte identical to {names(m['exact'])} from another submission.",
                           doc_id, None, {"matches": m["exact"], "sha256": sig["sha256"]}))
    if m["visual"]:
        out.append(Finding("visual_near_duplicate", MODULE, "soft", 4, cfg["p_visual"],
                           f"The first page looks almost identical to {names(m['visual'])} from another submission.",
                           doc_id, None, {"matches": m["visual"]}))
    if m["text"]:
        out.append(Finding("text_near_duplicate", MODULE, "soft", 3, cfg["p_text"],
                           f"The text is almost identical to {names(m['text'])} from another submission.",
                           doc_id, None, {"matches": m["text"]}))
    if not out:
        out.append(Finding("dedup_ok", MODULE, "info", 3, 0.0, "No duplicate found.", doc_id))
    return out


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m modules.dedup")
    ap.add_argument("file", help="file to check"); ap.add_argument("--against", nargs="*", default=[],
                                                                    help="files forming the index")
    ap.add_argument("--config")
    a = ap.parse_args(argv)
    cfg = load_config(a.config)
    idx = build_index([(Path(p).name, None, None, p) for p in a.against], cfg)
    fs = analyze(a.file, Path(a.file).name, idx, cfg=cfg)
    json.dump([f.to_json() for f in fs], sys.stdout, indent=2); print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
