"""Duplicate and near-duplicate detection: SHA-256, perceptual hash of page 1, MinHash over text.

Input : a PDF/image path, an Index of previously seen documents (build_index), optional
        inst_id / doc_type of the document being checked.
Output: list[Finding] (all soft):
          exact_duplicate        tier 3, p~0.8  byte-identical file (SHA-256) held by another document
          visual_near_duplicate  tier 4, p~0.5  (a) page-1 pHash within max_hamming_frac, for pairs with a
                                                raster page (copies of the same page), or (b) FIELD-REGION match:
                                                a scan whose variable-field text agrees with a digital document of
                                                the same type (re-scans of templated pages; evidence.method =
                                                "field_regions"). Image heuristic: advisory, never hard
          text_near_duplicate    tier 3, p~0.5  MinHash Jaccard of word shingles >= threshold
          dedup_ok (info), dedup_unreadable (info)
        evidence.matches lists the other documents (doc_id, inst_id, doc_type, similarity).
        Only the strongest kind is reported per pair (an exact copy is not also "near").
Symmetry: a pair is reported on BOTH members (there is no arrival order in a corpus); a live system
would check each new upload against the index of earlier ones.
Pure: no database or file writes. The index is an in-memory object built from signatures.
Template awareness: documents of one type are issued from one template, so their raw text is ~100%
similar and their page-1 pHashes collide. MinHash therefore drops, per doc type, shingles that are
frequent in train-split clean documents (config/dedup_boilerplate.yaml, harness.build_dedup_boilerplate).
Page-level pHash cannot see differences in a few field values, so it is only a screen for copies of
the same page; re-scans of templated pages are matched by the field-region channel instead: the
variable-field boxes of a document type are learned from the digital documents in the index (where
they differ from each other), and a scan is compared with each digital document of the type only
inside those boxes (background-normalised ink, best normalised cross-correlation within +-4 px,
mean over boxes). Needs >= field_min_digital digital documents of the type in the index. Not
handled: scan <-> scan pairs, a scan of a page whose fields were edited, pages with few variable boxes. Measured on clean scans (n=26): robust to JPEG re-save (max distance 0.027), re-scaling
(0.023) and contrast changes (0.016); NOT robust to brightness offsets that clip the page background
(+18 levels: median 0.052) or to any rotation (0.5 degrees: 0.11). See reports/BATCH_B_REPORT.md for the
measured limit on re-scanned templated pages.
Does NOT detect: reuse of a single seal or signature (all seals in the corpus are drawn alike),
a document pasted INTO a different page, re-typed content with a different layout, near-duplicates of
scans that lie about their content. Scans have no text layer, so MinHash is empty for them and only
the pHash applies. Blank pages get no pHash. By default only cross-institution pairs are reported
(config cross_institution_only) and fuzzy matches also need the same doc_type.
"""
